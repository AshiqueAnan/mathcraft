// gen-lesson-lite — emit a static, import-free prerequisite map for the
// progress engine, so the shared client bundle never pulls the full lesson
// registry (1.16 MB). Reads the lesson TS sources directly (regex on the
// authored data) and writes src/content/lesson-lite.ts (no imports).
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const DIR = join(ROOT, "src", "content", "lessons");
const OUT = join(ROOT, "src", "content", "lesson-lite.ts");

const files = readdirSync(DIR).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
const map = {};
for (const f of files) {
  const src = readFileSync(join(DIR, f), "utf8");
  const idM = /id:\s*"([^"]+)"/.exec(src);
  if (!idM) { console.error(`[${f}] no id`); process.exit(1); }
  const id = idM[1];
  const preM = /prerequisites:\s*(\[[^\]]*\])/.exec(src);
  let pre = [];
  if (preM) {
    try { pre = JSON.parse(preM[1].replace(/'/g, '"')); } catch { pre = []; }
  }
  map[id] = pre;
}

const body = `/**\n * Lightweight lesson metadata (auto-generated by scripts/gen-lesson-lite.mjs).\n * Contains ONLY the prerequisite graph — no lesson content — so the landing\n * page and shared client bundle stay small. Re-run the generator if the\n * curriculum's prerequisites change.\n */\nexport const PREREQUISITES: Record<string, string[]> = ${JSON.stringify(map, null, 2)};\n`;
writeFileSync(OUT, body);
console.log(`Wrote ${OUT} (${Object.keys(map).length} lessons, ${body.length} bytes).`);