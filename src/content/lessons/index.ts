export const BUILT_LESSON_IDS: string[] = BUILT_LESSONS.map((l) => l.id);

const byId = new Map<string, Lesson>(BUILT_LESSONS.map((l) => [l.id, l]));

/** Load a lesson by ID; undefined if not yet built (locked). */
export function getLesson(id: string): Lesson | undefined {
  return byId.get(id);
}

/** Human-readable title for any lesson ID (falls back to the ID for unbuilt lessons). */
export function lessonTitle(id: string): string {
  return byId.get(id)?.title ?? `Lesson ${id.split("-").pop() ?? id}`;
}
